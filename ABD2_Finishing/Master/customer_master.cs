        public string ErrorMessage = "";
        public bool Validate()
        {

            if ((string.IsNullOrEmpty(name.Text.Trim())))
            {
                ErrorMessage = "Name Should Not be Empty";
                name.Focus();
                return true;
            }
            if ((string.IsNullOrEmpty(Address.Text.Trim())))
            {
                ErrorMessage = "Address Should Not be Empty";
                Address.Focus();
                return true;
            }

            if ((string.IsNullOrEmpty(Phoneno.Text.Trim())))
            {
                ErrorMessage = "Phone No Should Not be Empty";
                Phoneno.Focus();
                return true;
            }
            if ((string.IsNullOrEmpty(Type.Text.Trim())))
            {
                ErrorMessage = "Please Select Customer Type";
                Type.Focus();
                return true;
            }
          
           

            return false;
        }
        public void insert()
        {
            DataTable dt = dbFunctions.getTable("Select CM_CustomerName from Customer_Master where CM_Phone1='" + Phoneno.Text + "'");
            if (dt.Rows.Count > 0)
            {
                ErrorMessage = "Phone No Already Exist on the Name of '" + dt.Rows[0]["CM_CustomerName"].ToString() + "' ";
                Phoneno.Focus();
                MessageBox.Show(ErrorMessage, "Error", MessageBoxButtons.OK, MessageBoxIcon.Exclamation);
                return ;
            }
            SqlConnection con = new SqlConnection(dbFunctions.connectionstring);
            try
            {
                con.Open();
                SqlCommand com = new SqlCommand();
                com.Connection = con;
                com.CommandType = CommandType.StoredProcedure;
                com.CommandText = "pr_InsertCustomerMaster";
                com.Parameters.Add("@CM_Code", SqlDbType.VarChar).Value = code.Text.ToString();
                com.Parameters.Add("@CM_CustomerName", SqlDbType.VarChar).Value = name.Text.ToString();
                com.Parameters.Add("@CM_Address", SqlDbType.VarChar).Value = Address.Text.ToString();
                com.Parameters.Add("@CM_City", SqlDbType.VarChar).Value = city.Text.ToString();
                com.Parameters.Add("@CM_State", SqlDbType.VarChar).Value = State.Text.ToString();
                com.Parameters.Add("@CM_Pincode", SqlDbType.VarChar).Value = pin.Text.ToString();
                com.Parameters.Add("@CM_Phone1", SqlDbType.VarChar).Value = Phoneno.Text.ToString();
                com.Parameters.Add("@CM_Email", SqlDbType.VarChar).Value = Email.Text.ToString();
                com.Parameters.Add("@CM_User", SqlDbType.VarChar).Value = dbFunctions.username;
                com.Parameters.Add("@CM_type", SqlDbType.VarChar).Value = Type.Text.ToString(); 
                
                com.ExecuteNonQuery();
                com.Connection.Close();
                MessageBox.Show("Details Saved Successfully ", "Sucess", MessageBoxButtons.OK, MessageBoxIcon.Information);
                Clear();
                display();
            }
            catch (Exception Ex)
            {
                dbFunctions.Logs(Ex.Message, dbFunctions.username);
                MessageBox.Show(Ex.Message, "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
            }

