        public bool Validate()
        {
            
            if ((string.IsNullOrEmpty(SM_SupplierName.Text.Trim())))
            {
                ErrorMessage = "SupplierName Should Not be Empty";
                SM_SupplierName.Focus();
                return true;
            }
            if ((string.IsNullOrEmpty(SM_Address.Text.Trim())))
            {
                ErrorMessage = "Address Should Not be Empty";
                SM_Address.Focus();
                return true;
            }
           
            return false;
        }
